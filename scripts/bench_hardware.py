"""Measure KAIROS workloads on this machine and write docs/benchmarks.md (K-1.08).

Usage:
    uv run python scripts/bench_hardware.py            # full run (~minutes)
    uv run python scripts/bench_hardware.py --quick    # smoke-sized run
    uv run python scripts/bench_hardware.py --out -    # print instead of writing

Measures:
    * Prophet fits/s, serial vs a pmap pool (default 28 workers)
    * NeuralProphet single-fit time, CPU vs GPU
    * Batched 4-parameter least squares: CPU float64 vs GPU float32
    * GPU matmul throughput: float32 vs float64 (TFLOPS)
"""

from __future__ import annotations

import argparse
import platform
import sys
from datetime import UTC, datetime
from pathlib import Path

from kairos.compute.bench import (
    BenchResult,
    bench_lstsq,
    bench_matmul,
    bench_neuralprophet,
    bench_prophet,
)
from kairos.compute.hardware import cpu_info, cuda_info, package_version, ram_bytes
from kairos.settings import get_settings


def _fmt(x: float, digits: int = 2) -> str:
    return f"{x:,.{digits}f}"


def run(quick: bool, n_jobs: int) -> str:
    cuda = cuda_info()
    gpu = cuda.available and bool(cuda.devices)
    cpu = cpu_info()
    lines: list[str] = []
    emit = lines.append

    def log(msg: str) -> None:
        print(msg, file=sys.stderr, flush=True)

    n_fits = 2 * n_jobs if quick else 32 * n_jobs
    n_serial = max(4, n_jobs if quick else 4 * n_jobs)
    log(f"Prophet: {n_serial} fits serial, {n_fits} fits with {n_jobs} workers ...")
    serial = bench_prophet(n_fits=n_serial, n_jobs=1)
    pooled = bench_prophet(n_fits=n_fits, n_jobs=n_jobs)

    epochs = 10 if quick else 50
    log("NeuralProphet: CPU ...")
    np_results = [bench_neuralprophet("cpu", epochs=epochs)]
    if gpu:
        log("NeuralProphet: GPU ...")
        np_results.append(bench_neuralprophet("gpu", epochs=epochs))

    batches = [1_000, 10_000] if quick else [1_000, 10_000, 100_000]
    lstsq: list[BenchResult] = []
    for batch in batches:
        log(f"lstsq batch={batch} ...")
        lstsq.append(bench_lstsq(batch, device="cpu"))
        if gpu:
            lstsq.append(bench_lstsq(batch, device="cuda"))
    if gpu:
        log("GPU batched lstsq at 1M problems ...")
        lstsq.append(bench_lstsq(1_000_000 if not quick else 200_000, device="cuda"))

    matmul: list[BenchResult] = []
    if gpu:
        size = 4096 if quick else 8192
        log("GPU matmul fp32/fp64 ...")
        matmul = [
            bench_matmul("float32", size=size, repeats=10),
            bench_matmul("float64", size=size // 2, repeats=3),
        ]

    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    emit("# Hardware benchmarks")
    emit("")
    emit(
        "Generated by `scripts/bench_hardware.py`"
        + (" (`--quick`)" if quick else "")
        + f" on {now}. Rerun after hardware, driver or dependency changes; later"
        " defaults (chunk sizes, CPU vs GPU per job) are taken from these numbers."
    )
    emit("")
    emit("## Machine")
    emit("")
    emit("| Item | Value |")
    emit("|---|---|")
    split = f"{cpu.performance_cores} P + {cpu.efficiency_cores} E" if cpu.is_hybrid else "n/a"
    emit(
        f"| CPU | {cpu.model} ({cpu.physical_cores} cores: {split}, {cpu.logical_cores} threads) |"
    )
    emit(f"| RAM | {ram_bytes() / 1024**3:.0f} GiB |")
    for dev in cuda.devices:
        emit(
            f"| GPU | {dev['name']}, {dev['total_bytes'] / 1024**3:.0f} GiB,"
            f" sm_{dev['capability']} |"
        )
    emit(f"| OS | {platform.platform()} |")
    emit(f"| Python | {platform.python_version()} |")
    emit(f"| torch | {cuda.torch_version} (CUDA {cuda.torch_cuda_build}) |")
    for pkg in ("numpy", "prophet", "neuralprophet", "cmdstanpy"):
        emit(f"| {pkg} | {package_version(pkg)} |")
    emit("")

    emit("## Prophet null-model fits (CPU)")
    emit("")
    emit("200 monthly points, no seasonality, `changepoint_prior_scale=0.3`, MAP fit.")
    emit("")
    emit("| Mode | Fits | Wall time (s) | Fits/s | Median fit (s) | Speed-up |")
    emit("|---|--:|--:|--:|--:|--:|")
    for r in (serial, pooled):
        emit(
            f"| {r.name} | {int(r.work)} | {_fmt(r.seconds)} | {_fmt(r.rate)} |"
            f" {_fmt(r.extra['median_fit_s'], 3)} | {_fmt(r.rate / serial.rate, 1)}x |"
        )
    emit("")

    emit("## NeuralProphet single fit")
    emit("")
    emit(f"200 monthly points, `n_lags=12`, `n_forecasts=6`, {epochs} epochs, batch 32.")
    emit("")
    emit("| Device | Wall time (s) | Epochs/s |")
    emit("|---|--:|--:|")
    for r in np_results:
        emit(f"| {r.name.split()[-1]} | {_fmt(r.seconds)} | {_fmt(r.rate)} |")
    emit("")

    emit("## Batched 4-parameter least squares (LPPLS inner solve)")
    emit("")
    emit("Normal equations over 200 points; CPU in float64 (reference), GPU in float32.")
    emit("")
    emit("| Device / dtype | Batch | Solves/s |")
    emit("|---|--:|--:|")
    for r in lstsq:
        emit(f"| {r.name.removeprefix('lstsq ')} | {r.extra['batch']:,} | {_fmt(r.rate, 0)} |")
    emit("")

    if matmul:
        emit("## GPU matmul throughput")
        emit("")
        emit("TF32 disabled, so float32 is true IEEE single precision.")
        emit("")
        emit("| dtype | Size | TFLOPS |")
        emit("|---|--:|--:|")
        for r in matmul:
            emit(f"| {r.name.split()[-1]} | {r.extra['size']} | {_fmt(r.rate / 1e12)} |")
        ratio = matmul[0].rate / matmul[1].rate
        emit("")
        emit(f"float32 / float64 ratio: **{ratio:.0f}x**.")
        emit("")

    emit("## Takeaways")
    emit("")
    emit(
        f"- Prophet: the {n_jobs}-worker pool gives {pooled.rate / serial.rate:.1f}x the"
        " serial throughput; keep fits on the CPU pool. Per-fit time rises inside the"
        f" pool ({serial.extra['median_fit_s']:.3f} s to {pooled.extra['median_fit_s']:.3f} s)"
        " because of all-core clocks, E-cores and CmdStan's per-fit subprocess and CSV"
        " I/O, so batch several fits per task where possible."
    )
    if len(np_results) == 2:
        cpu_s, gpu_s = np_results[0].seconds, np_results[1].seconds
        faster = "CPU" if cpu_s < gpu_s else "GPU"
        emit(
            f"- NeuralProphet single small fit: {faster} is faster"
            f" ({_fmt(cpu_s)} s CPU vs {_fmt(gpu_s)} s GPU); use the GPU only for"
            " batched ensembles or global models."
        )
    if gpu:
        best_cpu = max(r.rate for r in lstsq if "cpu" in r.name)
        best_gpu = max(r.rate for r in lstsq if "cuda" in r.name)
        emit(
            f"- Batched least squares: GPU float32 peaks at {best_gpu / best_cpu:.0f}x the"
            " CPU float64 rate; LPPLS grids go to the GPU with CPU float64 refinement."
        )
    if matmul:
        emit(
            "- FP64 on this GPU is a small fraction of FP32; do not port float64 kernels"
            " to the GPU as-is."
        )
    emit("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--quick", action="store_true", help="smoke-sized run")
    parser.add_argument("--n-jobs", type=int, default=None, help="pool size (default: settings)")
    parser.add_argument("--out", default="docs/benchmarks.md", help="output path or '-'")
    args = parser.parse_args()
    n_jobs = args.n_jobs or get_settings().n_jobs
    report = run(args.quick, n_jobs)
    if args.out == "-":
        print(report)
    else:
        path = Path(args.out)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(report, encoding="utf-8", newline="\n")
        print(f"wrote {path}", file=sys.stderr)


if __name__ == "__main__":
    main()
